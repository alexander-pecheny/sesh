#!/usr/bin/env python3
"""Records real Claude Code Transcripts, anonymised, into the corpus the parser tests replay
(core/sesh-transcript/tests/claude, whose README says when and how).

  uv run python scripts/claude-corpus.py list FILE
  uv run python scripts/claude-corpus.py record DIR FILE[:LINES]... [--all-types]
  uv run python scripts/claude-corpus.py recipe DIR RECIPE.json [--raw]

A recipe is {"sample": ["FILE:LINES", ...], ...}, recording each sample into DIR/sample with
one salt, so a word is the same made-up word across all of them. --raw writes the chosen
lines as they are, to check that the anonymised copy reads the same; never commit those.

`list` prints one line per Transcript line with only its structure, to choose LINES from,
such as `1-40,52,60-`. `record` writes each FILE's chosen lines into DIR, a subagent's under
DIR/subagents. Every word becomes a made-up word of the same length, the same word the same
made-up word within one run, and every digit run other digits. Field names, types, ids,
versions, timestamps, tags, and the notices Claude writes itself stay as they are. Lines the
parser never reads are left out unless --all-types is given."""
import hashlib, json, os, re, sys
from pathlib import Path

SALT = os.urandom(16)
VOWELS, CONSONANTS = "aeiou", "bcdfghjklmnprstvz"
PNG = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNkYAAAAAYAAjCB0C8AAAAASUVORK5CYII="

# Values under these keys are enums, ids, versions or times, which carry no user content.
KEEP = {
    "type", "subtype", "role", "stop_reason", "stop_sequence", "version", "timestamp", "uuid",
    "parentUuid", "logicalParentUuid", "leafUuid", "sessionId", "session_id", "agentId", "id",
    "tool_use_id", "toolUseID", "sourceToolUseID", "sourceToolAssistantUUID", "parentToolUseID",
    "promptId", "messageId", "requestId", "requestRef", "name", "status", "kind", "commandMode",
    "mode", "model", "requestedModel", "advisorModel", "userType", "entrypoint", "permissionMode",
    "level", "backgroundTaskId", "taskId", "task_id", "shell_id", "subagent_type",
    "run_in_background", "effort", "perTurnEffort", "service_tier", "speed", "inference_geo",
    "thinkingDisplay", "operation", "media_type", "attributionAgent", "error", "slug",
    "promptCacheRequested", "multiSelect", "isolation", "reason", "trigger", "taskKind", "cronKind", "cron",
}
IDS = {"uuid", "parentUuid", "sessionId", "agentId", "id", "tool_use_id", "toolUseID", "sourceToolUseID", "backgroundTaskId", "taskId", "task_id", "shell_id"}
# Values that are an image or a blob, which become a one-pixel PNG.
BLOB = {"data", "base64"}
SIGNATURE_KEEP = 96
# Words kept as they are: file extensions, which the parser reads to tell images apart.
EXTENSIONS = {"png", "jpg", "jpeg", "gif", "webp", "heic", "heif", "json", "jsonl", "md", "rs", "py", "txt", "output", "sh", "toml", "swift", "ts", "js", "html", "log"}
# Lines the parser reads; the rest are left out unless --all-types is given.
READ_TYPES = {"user", "assistant", "queue-operation", "system"}
READ_ATTACHMENTS = {"queued_command"}

# The tags Claude wraps its own notices and the user's commands in.
TAGS = [
    "task-notification", "task-id", "tool-use-id", "output-file", "status", "summary", "result", "usage",
    "subagent_tokens", "total_tokens", "tool_uses", "duration_ms", "note", "event", "system-reminder",
    "command-name", "command-message", "command-args", "local-command-stdout", "local-command-stderr",
    "local-command-caveat", "bash-input", "bash-stdout", "bash-stderr", "pasted_content", "tool_use_error",
    "fork-boilerplate", "user-prompt-submit-hook",
]
# Claude's own notices, kept word for word. A group named user is user content.
NOTICES = [re.compile(pattern, re.S) for pattern in [
    r"\A/[\w:-]+(?=\s|\Z)",
    r"\[Request interrupted by user[^\]\n]*\]",
    r"\[Image #\d+\]",
    r"\[Image: original [^\]\n]*\]",
    r"\[Pasted text #\d+[^\]\n]*\]",
    r"\[Monitor expired[^\]\n]*\]?",
    r"\[\d+ events? suppressed[^\]\n]*\]?",
    r"Caveat: The messages below were generated by the user[^\n<]*",
    r"This session is being continued from a previous conversation[^\n]*",
    r"<(status|tool-use-id|task-id|command-name|command-message|note|usage|local-command-caveat)>.*?</\1>",
    r"<summary>(?:Background command|Agent|Monitor event:|Monitor) \"(?P<user>(?:(?!</summary>).)*)\"[^\"<]*</summary>",
    r"\[Image: source: ",
    r"Command running in background with ID: [\w-]+\. Output is being written to: ",
    r"Command (?:was moved|did not complete within its \d+s timeout and was moved) to the background \(ID: [\w-]+\)[^/\n]*",
    r"Monitor started \(task [\w-]+, [^\n]*",
    r"Async agent launched successfully\.[^\n]*",
    r"\"message\":\"Successfully stopped task: [\w-]+ \(",
    r"This agent has not reported yet:[^\n<]*",
    r"&(?:[a-z]+|#\d+);",
    rf"</?(?:{'|'.join(TAGS)})(?:\s+id=\"[^\"]*\")?\s*/?>",
]]
TOKEN = re.compile(r"[^\W\d_]+|\d+")
ID = re.compile(r"[\w-]+")
ID_VALUE = re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|(?:msg|req|toolu|srvtoolu)_\w+")
# Longer text keeps only its head and tail, which hold every tag the parser reads.
LONG = 4000


def made_up(word):
    if word.lower() in EXTENSIONS:
        return word
    digest = hashlib.blake2b(word.encode(), key=SALT).digest()
    if word.isdigit():
        return "".join(str(digest[i % len(digest)] % 10) for i in range(len(word)))
    out = []
    for i, char in enumerate(word):
        byte = digest[i % len(digest)] ^ i
        letter = (VOWELS if i % 2 else CONSONANTS)[byte % (5 if i % 2 else 17)]
        out.append(letter.upper() if char.isupper() else letter)
    return "".join(out)


def words(text, ids):
    def word(m):
        return m.group(0) if m.group(0) in ids else TOKEN.sub(lambda t: made_up(t.group(0)), m.group(0))
    return ID.sub(word, text)


def text(value, ids):
    """Free text with Claude's notices and tags kept and everything else made up."""
    out, at = [], 0
    while at < len(value):
        found = [(m.start(), m) for m in (p.search(value, at) for p in NOTICES) if m]
        if not found:
            break
        start, match = min(found, key=lambda item: (item[0], -len(item[1].group(0))))
        out.append(words(value[at:start], ids))
        kept = match.group(0)
        if "user" in match.re.groupindex:
            a, b = match.span("user")
            kept = value[start:a] + words(value[a:b], ids) + value[b:match.end()]
        out.append(kept)
        at = match.end()
    out.append(words(value[at:], ids))
    return "".join(out)


def anonymise(value, ids, key=None):
    if isinstance(value, dict):
        return {(k if re.fullmatch(r"[A-Za-z_$][\w$]{0,40}", k) else text(k, ids)): anonymise(v, ids, k) for k, v in value.items()}
    if isinstance(value, list):
        return [anonymise(v, ids, key) for v in value]
    if not isinstance(value, str):
        return value
    if key in KEEP or ID_VALUE.fullmatch(value):
        return value
    if key in BLOB:
        return PNG
    if key == "signature":
        return value[:SIGNATURE_KEEP]
    if len(value) > LONG:
        value = value[: LONG // 2] + "\n…\n" + value[-LONG // 4 :]
    return text(value, ids)


def collect_ids(value, ids, key=None):
    """Every id the lines name, so a mention of one in free text stays matched to it."""
    if isinstance(value, dict):
        for k, v in value.items():
            collect_ids(v, ids, k)
    elif isinstance(value, list):
        for v in value:
            collect_ids(v, ids, key)
    elif isinstance(value, str):
        if key in IDS:
            ids.add(value)
        for tag in ("task-id", "tool-use-id"):
            ids.update(found.strip() for found in re.findall(rf"<{tag}>(.*?)</{tag}>", value))


def parse(text):
    """A line as what comes before it on the same line and its JSON, or None. Claude now and
    then leaves a line half-written and starts the next one on it; the half stays in front."""
    for start in [0] + [m.start() for m in re.finditer(r'\{"(?:parentUuid|type)"', text) if m.start()]:
        try:
            line = json.loads(text[start:])
        except ValueError:
            continue
        return (text[:start], line) if isinstance(line, dict) else None
    return None


def half(head, ids):
    """A half-written line, its keys and enum values kept and its other strings made up."""
    out, at, key = [], 0, None
    for m in re.finditer(r'"((?:[^"\\]|\\.)*)"(\s*:)?', head):
        out.append(head[at:m.start()])
        value = m.group(1)
        if m.group(2):
            key = value
            out.append(m.group(0))
        else:
            out.append('"' + (value if key in KEEP or ID_VALUE.fullmatch(value) else words(value, ids)) + '"')
        at = m.end()
    return "".join(out) + words(head[at:], ids)


def ranges(spec, count):
    if not spec:
        return set(range(1, count + 1))
    chosen = set()
    for part in spec.split(","):
        start, _, end = part.partition("-")
        chosen.update(range(int(start), (int(end) if end else count) + 1 if "-" in part else int(start) + 1))
    return chosen


def wanted(line, all_types):
    if all_types:
        return True
    if line.get("type") == "attachment":
        return (line.get("attachment") or {}).get("type") in READ_ATTACHMENTS
    return line.get("type") in READ_TYPES


def record(out, sources, all_types, raw=False):
    chosen = []
    for source in sources:
        path, _, spec = source.partition(":")
        raws = Path(path).read_text().splitlines()
        keep = ranges(spec, len(raws))
        lines = [line for n, text in enumerate(raws, 1) if n in keep and (line := parse(text))]
        chosen.append((Path(path), [(head, line) for head, line in lines if head or wanted(line, all_types)]))
    ids = set()
    for _, lines in chosen:
        collect_ids([line for _, line in lines], ids)
    mains = [path for path, _ in chosen if path.parent.name != "subagents"]
    for path, lines in chosen:
        if path in mains:
            folder, name = Path(out), "session.jsonl" if len(mains) == 1 else f"session-{mains.index(path) + 1}.jsonl"
        else:
            folder, name = Path(out) / "subagents", path.name
        folder.mkdir(parents=True, exist_ok=True)
        body = "".join(
            (head if raw else half(head, ids)) + json.dumps(line if raw else anonymise(line, ids), ensure_ascii=False, separators=(",", ":")) + "\n"
            for head, line in lines
        )
        (folder / name).write_text(body)
        print(f"{folder / name}: {len(lines)} lines")


def outline(line):
    parts = [str(line.get("type"))]
    for key in ("subtype", "operation"):
        if line.get(key):
            parts.append(str(line[key]))
    if line.get("type") == "attachment":
        parts.append(str((line.get("attachment") or {}).get("type")))
    for flag in ("isSidechain", "isMeta", "isCompactSummary"):
        if line.get(flag):
            parts.append(flag)
    if (line.get("origin") or {}).get("kind"):
        parts.append("origin=" + line["origin"]["kind"])
    message = line.get("message") or {}
    if message.get("stop_reason"):
        parts.append("stop=" + message["stop_reason"])
    content = message.get("content")
    for block in content if isinstance(content, list) else []:
        if not isinstance(block, dict):
            continue
        if block.get("type") == "tool_use":
            bg = " bg" if (block.get("input") or {}).get("run_in_background") in (True, "true") else ""
            parts.append(f"use:{block.get('name')}{bg}:{block.get('id', '')[-6:]}")
        elif block.get("type") == "tool_result":
            parts.append(f"result:{block.get('tool_use_id', '')[-6:]}")
        else:
            parts.append(str(block.get("type")))
    result = line.get("toolUseResult")
    if isinstance(result, dict):
        parts += [f"{k}={result[k]}" for k in ("status", "backgroundTaskId", "agentId") if result.get(k)]
    raw = json.dumps(line)
    for marker in ("<task-notification>", "still running", "[Request interrupted", "[Image", "<command-name>", "Monitor expired"):
        if marker in raw:
            parts.append(marker)
    status = re.search(r"<status>(\w+)</status>", raw)
    if status:
        parts.append("status=" + status.group(1))
    command = re.search(r"<command-name>(/[\w:-]+)</command-name>", raw)
    if command:
        parts.append(command.group(1))
    return " ".join(parts)


def main(args):
    if len(args) >= 2 and args[0] == "list":
        for path in args[1:]:
            prefix = f"{Path(path).name}:" if len(args) > 2 else ""
            for n, raw in enumerate(Path(path).read_text().splitlines(), 1):
                line = parse(raw)
                print(f"{prefix}{n}", ("half-written, then " if line and line[0] else "") + outline(line[1]) if line else "unreadable")
        return 0
    flags = {arg for arg in args if arg.startswith("--")}
    args = [arg for arg in args if arg not in flags]
    if len(args) >= 3 and args[0] == "record":
        record(args[1], args[2:], "--all-types" in flags, "--raw" in flags)
        return 0
    if len(args) == 3 and args[0] == "recipe":
        recipe = json.loads(Path(args[2]).read_text())
        for name, sources in recipe.items():
            record(Path(args[1]) / name, [os.path.expanduser(source) for source in sources], "--all-types" in flags, "--raw" in flags)
        return 0
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
